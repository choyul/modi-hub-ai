/**
 * 한글 자모 분해 — 계층 ②(퍼지 검색)의 오타 흡수를 위한 전처리.
 *
 * 왜 필요한가:
 *   Fuse.js 는 문자 단위 편집거리를 쓴다. 영어 workshop/worksop 은 8자 중 1자
 *   차이라 쉽게 잡히지만, 한글 "숍"/"샵" 은 눈에는 한 획 차이여도 유니코드로는
 *   완전히 다른 문자 1개다. 6자짜리 "그린워크숍룸" 에서 1자가 통째로 다르면
 *   유사도가 급락해 오타를 놓친다.
 *
 *   자모로 풀면 "숍" → ㅅㅗㅂ, "샵" → ㅅㅑㅂ 이 되어 3자 중 2자가 일치한다.
 *   "그린워크숍룸"(15자모) vs "그린워크샵룸"(15자모) 은 1자모 차이가 되어
 *   편집거리가 크게 줄고, 퍼지 검색이 의도대로 동작한다.
 */

const CHO = ['ㄱ','ㄲ','ㄴ','ㄷ','ㄸ','ㄹ','ㅁ','ㅂ','ㅃ','ㅅ','ㅆ','ㅇ','ㅈ','ㅉ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];
const JUNG = ['ㅏ','ㅐ','ㅑ','ㅒ','ㅓ','ㅔ','ㅕ','ㅖ','ㅗ','ㅘ','ㅙ','ㅚ','ㅛ','ㅜ','ㅝ','ㅞ','ㅟ','ㅠ','ㅡ','ㅢ','ㅣ'];
const JONG = ['','ㄱ','ㄲ','ㄳ','ㄴ','ㄵ','ㄶ','ㄷ','ㄹ','ㄺ','ㄻ','ㄼ','ㄽ','ㄾ','ㄿ','ㅀ','ㅁ','ㅂ','ㅄ','ㅅ','ㅆ','ㅇ','ㅈ','ㅊ','ㅋ','ㅌ','ㅍ','ㅎ'];

const BASE = 0xac00;   // '가'
const LAST = 0xd7a3;   // '힣'

/**
 * 완성형 한글을 초·중·종성으로 분해한다. 한글이 아닌 문자는 그대로 둔다.
 * 띄어쓰기 차이도 흡수하려고 공백은 제거한다.
 *
 *   '그린워크숍룸' → 'ㄱㅡㄹㅣㄴㅇㅝㅋㅡㅅㅗㅂㄹㅜㅁ'
 */
export function toJamo(text: string): string {
  let out = '';
  for (const ch of text) {
    const code = ch.charCodeAt(0);
    if (code >= BASE && code <= LAST) {
      const idx = code - BASE;
      out += CHO[Math.floor(idx / 588)];
      out += JUNG[Math.floor((idx % 588) / 28)];
      out += JONG[idx % 28];            // 받침 없으면 빈 문자열
    } else if (ch !== ' ') {
      out += ch.toLowerCase();
    }
  }
  return out;
}
